import * as XLSX from "xlsx";
import type { Commessa, Pannello } from "../types/excel";

export async function importaExcel(file: File): Promise<Commessa> {

  const buffer = await file.arrayBuffer();

  const workbook = XLSX.read(buffer);

  const sheet = workbook.Sheets[workbook.SheetNames[0]];

  const rows = XLSX.utils.sheet_to_json(sheet, {
    header: 1,
    defval: "",
  }) as unknown[][];

  // ==========================
  // DATI COMMESSA
  // ==========================

  const ordine = String(rows[1][1] ?? "");
  const cliente = String(rows[1][7] ?? "");
  const riferimento = String(rows[1][11] ?? "");

  const pannelli: Pannello[] = [];

  // ==========================
  // PANNELLI
  // ==========================

  for (let r = 4; r < rows.length; r++) {

    const row = rows[r];

    if (!row || row.length === 0)
      continue;

    if (row[1] === "")
      continue;

    pannelli.push({

      numeroMasterPanel: String(row[0]),

      numeroPannello: String(row[1]),

      numeroCliente: String(row[2] ?? ""),

      numeroCamion: String(row[3]),

      lato1: String(row[4]),

      lato2: String(row[5]),

      tipoPannello: String(row[6]),

      quantita: Number(row[7]),

      spessore: Number(row[8]),

      lunghezza: Number(row[9]),

      altezza: Number(row[10]),

      superficie: Number(row[11]),

      volume: Number(row[12]),

      peso: Number(row[13]),

      preparato: false,
      
      caricato: false,

    });

  }

  console.log("Commessa:", ordine);
  console.log("Cliente:", cliente);
  console.log("Riferimento:", riferimento);
  console.log("Pannelli:", pannelli.length);

  return {

    ordine,

    cliente,

    numeroCliente: "",

    riferimento,

    pannelli

  };

}


































































































































































































































































































































































































































































































































































































































































































































































































































































































